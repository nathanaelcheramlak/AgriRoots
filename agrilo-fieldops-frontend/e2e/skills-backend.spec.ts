test('required date inputs and authorized farm handoff precede one real controlled skill run', async ({ page }) => {
  await login(page); await skills(page)
  const dialog = await inspect(page, 'skills_fixture_dates')
  await dialog.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await dialog.getByRole('button', { name: 'Open skill in Home', exact: true }).click()
  await expect(page).toHaveURL(/#skills$/)
  expect(await dialog.getByLabel('Skill input start', { exact: true }).evaluate((el: HTMLInputElement) => el.validity.valueMissing)).toBe(true)
  await dialog.getByLabel('Skill input start', { exact: true }).fill('2025-07-01')
  await dialog.getByLabel('Skill input end', { exact: true }).fill('2025-07-07')
  await dialog.getByRole('button', { name: 'Open skill in Home', exact: true }).click()
  await expect(page.getByLabel('start', { exact: true })).toHaveValue('2025-07-01')
  await expect(page.getByLabel('end', { exact: true })).toHaveValue('2025-07-07')
  await page.getByRole('checkbox', { name: /Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact: true }).fill('Explain the dated fixture evidence and its limits.')
  const created = page.waitForResponse(r => r.request().method() === 'POST' && /\/skills\/[^/]+\/runs$/.test(new URL(r.url()).pathname))
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  const response = await created
  expect(response.status()).toBe(202)
  const request = response.request().postDataJSON()
  expect(request.parameters).toEqual({ start: '2025-07-01', end: '2025-07-07' })
  expect(request.plot_ids).toHaveLength(1); expect(request.authorize_credit_use).toBe(false)
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Completed', { timeout: 30000 })
  await expect(page.locator('.live-evidence')).toHaveCount(1)
})

test('admin creates an explicit draft, validates without model/provider use, approves and enables an exact version', async ({ page }) => {
  let runs = 0
  page.on('request', r => { if (r.method() === 'POST' && /\/skills\/[^/]+\/runs$/.test(new URL(r.url()).pathname)) runs++ })
  await login(page, true); await skills(page)
  await page.getByRole('button', { name: 'Create skill draft', exact: true }).click()
  const manifest = { name: 'skills_browser_authored', description: 'Explicit office weather evidence workflow', instructions: 'Use approved weather evidence and cite source limitations. Fixture only.', required_capabilities: ['weather.forecast'], optional_capabilities: [], allowed_internal_actions: [], max_followup_rounds: 2, triggers: ['explicit_chat_request'] }
  await page.getByLabel('Skill manifest (JSON)', { exact: true }).fill(JSON.stringify(manifest))
  await page.getByRole('button', { name: 'Save backend draft', exact: true }).click()
  let dialog = await inspect(page, manifest.name)
  await expect(dialog.getByRole('button', { name: 'Open skill in Home', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Approve current skill version', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Validate this exact skill configuration')
  await dialog.getByRole('button', { name: 'Validate current configuration', exact: true }).click()
  await expect(dialog.getByText(/Configuration validation only; no model or provider request/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Approve current skill version', exact: true }).click()
  await dialog.getByRole('button', { name: 'Enable current skill version', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Open skill in Home', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Create skill revision', exact: true }).click()
  await page.getByLabel('Skill manifest (JSON)', { exact: true }).fill(JSON.stringify({ ...manifest, description: 'New unapproved weather draft' }))
  await page.getByRole('button', { name: 'Save backend draft', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByText('A newer definition is separate from the enabled version.', { exact: false })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Open skill in Home', exact: true })).toBeEnabled()
  expect(runs).toBe(0)
})


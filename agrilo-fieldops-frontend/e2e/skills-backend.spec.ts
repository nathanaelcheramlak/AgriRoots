import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

test.skip(!process.env.AGRI_SKILLS_FIXTURE, 'Requires the isolated Skills/Home/Plugins backend runner.')
async function login(page: Page, admin = false) {
  const ready = JSON.parse(readFileSync(process.env.AGRI_HOME_READY!, 'utf8'))
  expect(ready.fixture).toBe(true)
  const user = admin ? ready.admin : ready
  await page.route('https://**/*', route => route.abort())
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact: true }).fill(user.phone)
  await page.getByLabel('Password', { exact: true }).fill(user.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('main', { name: 'Live officer companion' })).toBeVisible()
}
async function skills(page: Page) {
  await page.getByRole('link', { name: 'Skills', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Inspect skill home_fixture_combined', exact: true })).toBeVisible()
}
async function inspect(page: Page, name: string) {
  await page.getByRole('button', { name: `Inspect skill ${name}`, exact: true }).click()
  return page.getByRole('dialog')
}

test('Skills handoff uses the existing Home executor/evidence and preserves active work and map context', async ({ page }) => {
  const posts: unknown[] = []
  page.on('request', request => { if (request.method() === 'POST' && /\/skills\/[^/]+\/runs$/.test(new URL(request.url()).pathname)) posts.push(request.postDataJSON()) })
  await login(page)
  await page.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await page.getByRole('button', { name: 'Expand map', exact: true }).click()
  await skills(page)
  let dialog = await inspect(page, 'home_fixture_combined')
  await expect(dialog.getByRole('checkbox', { name: /Synthetic plot A/ })).toBeChecked()
  await expect(dialog.getByText('weather.forecast · Required · Approved enabled tool available for your role', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Open skill in Home', exact: true }).click()
  await expect(page).toHaveURL(/#home$/)
  await expect(page.getByRole('button', { name: 'Compact map', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: /Synthetic plot A/ })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: /Authorize the selected skill/ })).not.toBeChecked()
  expect(posts).toHaveLength(0)
  await page.getByRole('checkbox', { name: /Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact: true }).fill('[skills-fixture-pause] Inspect forecast and soil with actual fixture evidence and limitations.')
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  await skills(page)
  dialog = await inspect(page, 'home_fixture_combined')
  await expect(dialog.getByRole('button', { name: 'Open skill in Home', exact: true })).toBeDisabled()
  await dialog.getByRole('link', { name: 'Return to the active Home investigation', exact: true }).click()
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Completed', { timeout: 30000 })
  await expect(page.locator('.live-evidence')).toHaveCount(2)
  await expect(page.getByRole('img', { name: /precipitation_sum:/ })).toBeVisible()
  expect(posts).toHaveLength(1)
  await page.getByRole('link', { name: 'Plugins', exact: true }).click()
  await expect(page.getByText('14 implemented', { exact: true })).toBeVisible()
  await skills(page)
  await inspect(page, 'home_fixture_combined')
  await expect(page.getByRole('dialog').getByText(/Inspect forecast and soil with actual fixture/)).toBeVisible()
  await page.screenshot({ path: 'test-results-skills/skills-evidence-history.png', fullPage: true })
})


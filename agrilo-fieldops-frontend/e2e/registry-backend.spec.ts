import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

test.skip(!process.env.AGRI_HOME_READY, 'Requires the isolated PostGIS browser runner.')
function loginInfo() { return JSON.parse(readFileSync(process.env.AGRI_HOME_READY!, 'utf8')) }
async function signIn(page: Page) {
  const fixture = loginInfo()
  await page.route('https://**/*', r => r.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#456145"/><path d="M0 128H256 M128 0V256" stroke="#779477"/></svg>' }))
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact:true }).fill(fixture.phone)
  await page.getByLabel('Password', { exact:true }).fill(fixture.password)
  await page.getByRole('button', { name:'Sign in', exact:true }).click()
  await expect(page.getByRole('main', { name:'Agricultural map workspace' })).toBeVisible()
}
async function draw(page: Page, kind: 'overview' | 'farm', a = [.35,.35], b = [.65,.65]) {
  const map = page.locator('.area-canvas-'+kind+' .leaflet-container')
  await map.scrollIntoViewIfNeeded()
  const box = await map.boundingBox(); expect(box).not.toBeNull()
  await map.click({ position: { x:box!.width*a[0], y:box!.height*a[1] } })
  await map.click({ position: { x:box!.width*b[0], y:box!.height*b[1] } })
}

test('two maps: select outer area, draw only on crop, save three fields, relogin, run existing AI/evidence', async ({page}) => {
  const fixture = loginInfo(); expect(fixture.registry_postgis).toBe(true)
  const auth = await page.request.post('/backend/api/auth/login', { data:{phone_number:fixture.admin.phone,password:fixture.admin.password} })
  const headers = { Authorization:'Bearer '+(await auth.json()).access_token }
  const proposed = await page.request.post('/backend/api/v1/registry/territory-proposals', {headers,data:{name:'Assigned browser area',boundary:{type:'Polygon',coordinates:[[[38.7,9],[38.8,9],[38.8,9.1],[38.7,9.1],[38.7,9]]]}}})
  expect(proposed.status()).toBe(201); const territory = await proposed.json()
  expect((await page.request.post(`/backend/api/v1/registry/territories/${territory.id}/review`, {headers,data:{decision:'approve',expected_revision:1}})).status()).toBe(200)
  expect((await page.request.post(`/backend/api/v1/registry/territories/${territory.id}/assignments`, {headers,data:{user_id:fixture.registry_officer_id}})).status()).toBe(201)
  await signIn(page)
  await expect(page.locator('.area-canvas-overview .leaflet-container')).toBeVisible()
  const overview = await page.locator('.area-canvas-overview').boundingBox()
  expect(overview!.width).toBeGreaterThan(1000)
  await expect(page.getByRole('dialog',{name:'Farm AI Chat'})).toHaveCount(0)
  await expect(page.locator('.area-canvas-farm')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Assigned browser area',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Draw area',exact:true}).click()
  await draw(page,'overview')
  await expect(page.locator('.area-canvas-farm .leaflet-container')).toBeVisible()
  await expect(page.getByRole('button',{name:'Draw farm plot',exact:true})).toBeEnabled()
  // Both maps are independent: clicking the overview cannot produce a farm form.
  await page.getByRole('button',{name:'Change area',exact:true}).click()
  await draw(page,'overview',[.45,.45],[.55,.55])
  await expect(page.getByRole('form',{name:'Farmer details'})).toHaveCount(0)
  await expect(page.locator('.leaflet-container')).toHaveCount(2)
  await page.getByRole('button',{name:'Hide overview',exact:true}).click()
  await page.getByRole('button',{name:'Draw farm plot',exact:true}).click()
  await draw(page,'farm',[.4,.4],[.55,.55])
  const form = page.getByRole('form',{name:'Farmer details'})
  await expect(form).toBeVisible(); await expect(form.locator('input')).toHaveCount(3)
  await form.getByLabel('Farmer name',{exact:true}).fill('Test Map Farmer')
  await form.getByLabel('Farmer ID',{exact:true}).fill('MAP-DEMO-001')
  await form.getByLabel('Phone number',{exact:true}).fill('+251911112233')
  const saved = page.waitForResponse(r => r.request().method()==='POST' && r.url().includes('/farm-registrations'))
  await form.getByRole('button',{name:'Save farm',exact:true}).click()
  const response = await saved; expect(response.status()).toBe(201); const farm = await response.json()
  expect(farm.id).not.toMatch(/^local-/)
  await expect(page.getByRole('button',{name:'AI Chat',exact:true})).toBeEnabled()
  expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('Test Map Farmer')
  expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('+251911112233')
  // Artificial fixture record, explicitly marked by the administrator; no real-farm privacy override.
  expect((await page.request.patch('/backend/api/v1/registry/plots/'+farm.id,{headers,data:{name:farm.name,geometry:farm.geometry,farmer_ids:farm.farmerIds,synthetic:true,expected_revision:farm.revision,request_key:crypto.randomUUID()}})).status()).toBe(200)
  await page.reload(); await signIn(page)
  await page.getByRole('button',{name:'Assigned browser area',exact:true}).click()
  await page.getByRole('button',{name:/Farm MAP-DEMO-001/}).click()
  await page.getByRole('button',{name:'AI Chat',exact:true}).click()
  const chat = page.getByRole('dialog',{name:'Farm AI Chat'})
  await expect(chat.getByRole('combobox',{name:'Analysis',exact:true})).toBeVisible()
  await chat.getByRole('checkbox',{name:/Allow this analysis/}).check()
  await chat.getByLabel('Farming idea or question',{exact:true}).fill('Inspect the farm weather and mapped soil. Explain source limitations.')
  await chat.getByRole('button',{name:'Start analysis',exact:true}).click()
  await expect(chat.locator('.live-run').getByRole('status')).toContainText('Completed',{timeout:30000})
  await expect(chat.locator('.live-evidence')).toHaveCount(2)
  await expect(chat.getByRole('img',{name:/precipitation_sum:/})).toBeVisible()
  await page.screenshot({path:'test-results-registry/map-first-evidence.png',fullPage:true})
  await chat.getByRole('button',{name:'Close chat',exact:true}).click()
  await page.getByRole('link',{name:'Plugins',exact:true}).click()
  await page.getByRole('link',{name:'Home',exact:true}).click()
  await expect(page.locator('.area-canvas-farm')).toBeVisible()
  await page.getByRole('button',{name:'AI Chat',exact:true}).click()
  await expect(page.locator('.live-evidence')).toHaveCount(2)
})

test('mobile crop and three-field form remain usable without horizontal overflow', async ({page}) => {
  await page.setViewportSize({width:390,height:844}); await signIn(page)
  await page.getByRole('button',{name:'Assigned browser area',exact:true}).click()
  await page.getByRole('button',{name:'Draw farm plot',exact:true}).click()
  await draw(page,'farm',[.2,.6],[.35,.7])
  const form = page.getByRole('form',{name:'Farmer details'})
  await expect(form.locator('input')).toHaveCount(3)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
  await page.screenshot({path:'test-results-registry/map-first-mobile.png',fullPage:true})
  await form.getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(form).toHaveCount(0)
})

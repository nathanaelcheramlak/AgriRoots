import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

test.skip(!process.env.AGRI_HOME_READY, 'Requires isolated actual PostGIS registry runner.')
async function signIn(page: Page, login: { phone: string; password: string }) {
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact: true }).fill(login.phone)
  await page.getByLabel('Password', { exact: true }).fill(login.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.field-map')).toBeVisible({ timeout: 30000 })
}
async function coordinates(page: Page, values: number[]) {
  const drawer = page.locator('.territory-drawer')
  await drawer.getByText('Enter boundary coordinates', { exact: true }).click()
  for (const [i, label] of ['west','south','east','north'].entries()) await drawer.getByLabel(label, { exact: true }).fill(String(values[i]))
  await drawer.getByRole('button', { name: 'Preview coordinates', exact: true }).click()
}

test('actual PostGIS: territory proposal → approval/assignment → officer registration → relogin → farm investigation/evidence', async ({ page }) => {
  const fixture = JSON.parse(readFileSync(process.env.AGRI_HOME_READY!, 'utf8'))
  expect(fixture.registry_postgis).toBe(true)
  await page.route('https://**/*', r => r.abort())
  await signIn(page, fixture.admin)
  await page.getByRole('region', { name:'Territory workspace controls' }).getByRole('button', { name:'Set Up My Territory', exact:true }).click()
  const drawer = page.locator('.territory-drawer')
  await drawer.getByLabel('Territory name', { exact:true }).fill('PostGIS browser test territory')
  await drawer.getByLabel('Region', { exact:true }).fill('Test region')
  await drawer.getByLabel('District / administrative area', { exact:true }).fill('Test district')
  await coordinates(page, [38.60,8.80,38.70,8.90])
  await drawer.getByRole('button', { name:'Submit territory for approval', exact:true }).click()
  await expect(drawer.getByRole('button', { name:'Approve territory boundary', exact:true })).toBeVisible()
  await drawer.getByRole('button', { name:'Approve territory boundary', exact:true }).click()
  await drawer.getByLabel('Assign office staff').selectOption(fixture.registry_officer_id)
  await drawer.getByRole('button', { name:'Assign territory manager', exact:true }).click()
  await expect(drawer.getByText(new RegExp(fixture.registry_officer_id + ' · manager'))).toBeVisible()
  await drawer.getByRole('button', { name:'Close territory panel', exact:true }).click()
  await page.getByRole('button', { name:'Sign out', exact:true }).click()
  await signIn(page, fixture)
  await expect(page.locator('.territory-current')).toContainText('PostGIS browser test territory')
  await page.getByRole('button', { name:'My Territory', exact:true }).click()
  await drawer.getByRole('button', { name:'Register Farmer', exact:true }).click()
  await drawer.getByLabel('Farmer name', { exact:true }).fill('Test Farmer Browser 001')
  await drawer.getByLabel('Farmer reference ID', { exact:true }).fill('BROWSER-DEMO-001')
  await drawer.getByLabel('Telephone (optional, restricted)', { exact:true }).fill('+251911112233')
  await drawer.getByRole('button', { name:'Save Farmer to Registry', exact:true }).click()
  await expect(drawer.getByRole('heading', { name:'Test Farmer Browser 001', exact:true })).toBeVisible()
  await drawer.getByRole('button', { name:'Close territory panel', exact:true }).click()
  await page.getByRole('button', { name:'Register Farm Plot', exact:true }).click()
  await page.keyboard.press('Escape')
  await drawer.getByLabel('Farm name / plot label', { exact:true }).fill('Browser maize test plot')
  await coordinates(page, [38.61,8.81,38.611,8.811])
  await drawer.getByRole('checkbox', { name:/Test Farmer Browser 001/ }).check()
  await drawer.getByRole('combobox', { name:'Crop type', exact:true }).selectOption('Maize')
  await drawer.getByRole('button', { name:'Review registration', exact:true }).click()
  const created = page.waitForResponse(r => r.request().method() === 'POST' && /\/territories\/[^/]+\/plots$/.test(new URL(r.url()).pathname))
  await drawer.getByRole('button', { name:'Register Farm Plot', exact:true }).click()
  const response = await created; expect(response.status()).toBe(201)
  const plot = await response.json()
  await expect(drawer.getByRole('heading', { name:'Browser maize test plot', exact:true })).toBeVisible()
  await expect(drawer.getByText('Test Farmer Browser 001 · BROWSER-DEMO-001')).toBeVisible()
  expect(plot.id).not.toMatch(/^local-/)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('+251911112233')
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('Test Farmer Browser')
  // This disposable farm is artificial. Only its administrator can label it synthetic.
  const login = await page.request.post('/backend/api/auth/login', { data: { phone_number:fixture.admin.phone,password:fixture.admin.password } })
  const token = (await login.json()).access_token
  const marked = await page.request.patch('/backend/api/v1/registry/plots/'+plot.id, { headers: { Authorization:'Bearer '+token }, data:{
    name:plot.name, geometry:plot.geometry, farmer_ids:plot.farmerIds, synthetic:true, expected_revision:plot.revision, request_key:crypto.randomUUID(), season:{crop:'Maize'} } })
  expect(marked.status()).toBe(200)
  await page.reload(); await signIn(page, fixture)
  await expect(page.locator('.territory-current')).toContainText('PostGIS browser test territory')
  await page.getByRole('button', { name:'My Territory', exact:true }).click()
  await drawer.getByRole('button', { name:/Browser maize test plot · registered/ }).click()
  await expect(drawer.getByText('Test Farmer Browser 001 · BROWSER-DEMO-001')).toBeVisible()
  await drawer.getByRole('button', { name:'Select for Analysis', exact:true }).click()
  await page.getByRole('checkbox', { name:/Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name:/Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact:true }).fill('Inspect the registered farm weather and soil using the approved tools. Explain evidence limitations.')
  await page.getByRole('button', { name:'Start investigation', exact:true }).click()
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Completed', { timeout:40000 })
  await expect(page.locator('.live-evidence')).toHaveCount(2)
  await expect(page.getByRole('img', { name:/precipitation_sum:/ })).toBeVisible()
  await page.screenshot({path:'test-results-registry/registered-farm-evidence.png',fullPage:true})
})

test('draws, edits and removes a real rectangle using map geometry', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', { name: 'Draw rectangle', exact: true }).click()
  const box = (await page.locator('.field-map').boundingBox())!
  await page.mouse.click(box.x + box.width * .28, box.y + box.height * .28)
  await page.mouse.move(box.x + box.width * .76, box.y + box.height * .63, { steps: 8 })
  await page.mouse.click(box.x + box.width * .76, box.y + box.height * .63)
  await expect(page.locator('.selection-card')).toBeVisible()
  await expect(page.getByTestId('metric-farms')).not.toHaveText('—')
  const before = await page.locator('.selection-card').innerText()
  await page.getByRole('button', { name: 'Edit selection', exact: true }).click()
  const handle = page.locator('.marker-icon.leaflet-marker-draggable').first()
  await expect(handle).toBeVisible()
  const h = (await handle.boundingBox())!
  await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await page.mouse.down()
  await page.mouse.move(h.x + h.width / 2 + 40, h.y + h.height / 2 + 30, { steps: 10 }); await page.mouse.up()
  await expect(page.locator('.selection-card')).not.toHaveText(before)
  await page.getByRole('button', { name: 'Finish editing selection', exact: true }).click()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(page.locator('.farm-marker')).toHaveCount(0)
  await expect(page.locator('.selection-card')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Awaiting a field area' })).toBeVisible()
})
test('genuine empty area, layer toggles, and clear selection remove stale details', async ({ page }) => {
  await loadDemo(page)
  await page.getByRole('button', { name: 'Map layers' }).click(); await page.getByLabel('Farm locations', { exact: true }).uncheck()
  await expect(page.locator('.farm-marker')).toHaveCount(0); await page.getByLabel('Farm locations', { exact: true }).check()
  await expect(page.locator('.farm-marker')).toHaveCount(12)
  await expect(page.getByText('Satellite basemap', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: 'Street basemap' }).check()
  await expect(page.locator('.leaflet-control-attribution')).toContainText('OpenStreetMap')
  await expect(page.locator('.farm-marker')).toHaveCount(12)
  await page.getByRole('radio', { name: 'Satellite basemap' }).check()
  await expect(page.locator('.leaflet-control-attribution')).toContainText('Google Maps')
  await page.getByRole('button', { name: 'Map layers' }).click()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Zoom out', exact: true }).click()
  const box = (await page.locator('.field-map').boundingBox())!
  await page.getByRole('button', { name: 'Draw rectangle', exact: true }).click()
  await page.mouse.click(box.x + box.width * .68, box.y + box.height * .65)
  await page.mouse.click(box.x + box.width * .73, box.y + box.height * .70)
  await expect(page.getByRole('heading', { name: '0 farms found', exact: true })).toBeVisible()
  await expect(page.getByTestId('metric-farms')).toHaveText('0')
  await expect(page.locator('.farm-marker')).toHaveCount(0)
})

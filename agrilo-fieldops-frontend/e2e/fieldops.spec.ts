import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
async function loadDemo(page: Page) {
  await page.goto('/'); await page.getByRole('button', { name: 'Try demo area' }).first().click()
  await expect(page.getByTestId('metric-farms')).toHaveText('12')
  await expect(page.locator('.farm-marker')).toHaveCount(12)
}
test('loads real Leaflet, handles tile availability, and screens only the selected farms', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await loadDemo(page)
  await expect(page.getByRole('button', { name: 'Draw rectangle', exact: true })).toBeVisible()
  await expect(page.locator('.leaflet-control-attribution')).toContainText('Google Maps')
  await expect(page.locator('.leaflet-tile-loaded').first().or(page.locator('.tile-status').filter({ hasText: 'could not load' })).first()).toBeVisible({ timeout: 20000 })
  await expect(page.getByRole('heading', { name: 'Your area, at a glance.' })).toBeVisible()
  await expect(page.getByTestId('map-count')).toHaveText('12 farm markers shown')
  await expect(page.locator('.coordinate-widget')).toContainText('km²')
  await page.screenshot({ path: 'test-results/desktop-workspace.png', fullPage: true })
  expect(errors).toEqual([])
})

import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function homeSnapshot(page: Page) {
  return page.evaluate(async () => {
    const modulePath = '/src/state/useFieldOps.ts'
    const { fieldOpsStore } = await import(/* @vite-ignore */ modulePath) as typeof import('../src/state/useFieldOps')
    const s = fieldOpsStore.getState()
    return { selection: s.selection, selectedFarmId: s.selectedFarmId, filters: s.filters, analysis: s.analysis, messages: s.messages, tab: s.tab, phase: s.phase, assistantBusy: s.assistantBusy }
  })
}
async function loadDemo(page: Page) { await page.goto('/#home'); await page.getByRole('button', { name: /Try demo area/ }).first().click(); await expect(page.getByRole('heading', { name: 'Your area, at a glance.' })).toBeVisible() }

test('catalog adds local drafts with separate statuses and makes no external requests', async ({ page, baseURL }) => {
  const outside: string[] = [], errors: string[] = []
  page.on('request', request => { if (new URL(request.url()).origin !== new URL(baseURL!).origin) outside.push(request.url()) }); page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#plugins')
  await expect(page.getByText('No plugins saved yet.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save FAO GAEZ draft', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Save Open-Meteo draft', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Plugin details' })
  await expect(dialog.getByText('Setup available', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Not submitted', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Not enabled', { exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: 'Tools & operations', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Discover MCP tools' })).toBeDisabled()
  await dialog.getByRole('tab', { name: 'Testing & approval', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Test connection', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await page.screenshot({ path: 'test-results/plugins-catalog.png' })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Manage Open-Meteo', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('agrilo-fieldops:plugins:v1')!).drafts.length)).toBe(1)
  await page.getByRole('button', { name: 'Office', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'An office catalog, when you’re ready.' })).toBeVisible()
  expect(outside).toEqual([]); expect(errors).toEqual([])
})

test('custom API validates URLs, persists authentication method only, edits and removes', async ({ page }) => {
  const requests: string[] = []; page.on('request', request => { if (request.url().includes('field-api.example')) requests.push(request.url()) })
  await page.goto('/#plugins'); await page.getByRole('button', { name: 'Add plugin', exact: true }).click(); await page.getByRole('menuitem', { name: /Add API plugin/ }).click()
  let dialog = page.getByRole('dialog', { name: 'Add API plugin' })
  await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Office field API')
  await dialog.getByRole('textbox', { name: 'Base URL', exact: true }).fill('https://field-api.example/v1?api_key=never-persist-this')
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(dialog.getByText(/Use a credential-free HTTPS URL/)).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('agrilo-fieldops:plugins:v1'))).toBeNull()
  await dialog.getByRole('textbox', { name: 'Base URL', exact: true }).fill('https://field-api.example/v1')
  await dialog.getByRole('combobox', { name: 'Authentication method', exact: true }).selectOption('api_key')
  await dialog.getByRole('textbox', { name: 'API key header name', exact: true }).fill('X-Field-Key')
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Plugin details' })
  await expect(dialog.getByRole('heading', { name: 'Office field API', exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: 'Configuration', exact: true }).click()
  await expect(dialog.getByText('https://field-api.example/v1', { exact: true })).toBeVisible()
  const stored = await page.evaluate(() => localStorage.getItem('agrilo-fieldops:plugins:v1'))
  expect(stored).not.toContain('never-persist-this'); expect(stored).not.toMatch(/approved|enabled|health|credential/)
  await dialog.getByRole('button', { name: 'Edit', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Edit API plugin' }); await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Updated office API')
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Plugin details' }); await expect(dialog.getByRole('heading', { name: 'Updated office API', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Remove local draft', exact: true }).click()
  await expect(page.getByText('No plugins saved yet.', { exact: true })).toBeVisible()
  expect(requests).toEqual([])
})


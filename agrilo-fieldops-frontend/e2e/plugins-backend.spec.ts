import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

test.skip(!process.env.AGRI_PLUGINS_FIXTURE, 'Requires the isolated real REST/MCP backend fixture runner.')
type Ready = { phone: string; password: string; fixture: boolean; admin: { phone: string; password: string }; rest_origin: string; mcp_endpoint: string }
const ready = (): Ready => JSON.parse(readFileSync(process.env.AGRI_HOME_READY!, 'utf8'))
async function login(page: Page, admin = true) {
  const fixture = ready(), user = admin ? fixture.admin : fixture
  expect(fixture.fixture).toBe(true)
  await page.route('https://**/*', route => route.abort())
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact: true }).fill(user.phone)
  await page.getByLabel('Password', { exact: true }).fill(user.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('main', { name: 'Live officer companion' })).toBeVisible()
  await page.getByRole('link', { name: 'Plugins', exact: true }).click()
  await expect(page.getByText('14 implemented', { exact: true })).toBeVisible()
}
async function register(page: Page, kind: 'REST API' | 'MCP server', name: string, endpoint: string) {
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: kind === 'REST API' ? 'Register custom REST API' : 'Register MCP server', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('Name', { exact: true }).fill(name)
  await form.getByLabel(kind === 'REST API' ? 'Base URL (origin only)' : 'MCP server URL', { exact: true }).fill(endpoint)
  await form.getByRole('button', { name: 'Create disabled connection', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name, exact: true })).toBeVisible()
}


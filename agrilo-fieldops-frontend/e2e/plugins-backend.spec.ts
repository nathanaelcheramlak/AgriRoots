test('MCP register → actual SDK discovery → untrusted definition review → test/approve/enable', async ({ page }) => {
  await login(page)
  await register(page, 'MCP server', 'Phase2 browser MCP', ready().mcp_endpoint)
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: 'Testing & approval' }).click()
  await dialog.getByRole('checkbox', { name: 'Authorize network requests for discovery/tests', exact: true }).check()
  await dialog.getByRole('button', { name: 'Discover MCP tools', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('succeeded', { timeout: 30000 })
  await dialog.getByRole('tab', { name: 'Tools & operations' }).click()
  const lookup = dialog.locator('.managed-tool').filter({ hasText: 'upstream_tool_name' }).filter({ hasText: 'lookup' }).first()
  const raw = await lookup.locator('pre').textContent(), spec = JSON.parse(raw!) as Record<string, unknown>
  const name = spec.name as string
  expect(spec.capability_tags).toEqual(['unreviewed.mcp'])
  await lookup.getByRole('button', { name: `Review operation ${name}`, exact: true }).click()
  spec.description = 'Administrator reviewed synthetic MCP lookup; not agricultural field evidence.'
  spec.capability_tags = ['reference.lookup']
  await page.getByLabel('Operation definition (JSON)', { exact: true }).fill(JSON.stringify(spec))
  await page.getByRole('button', { name: 'Save reviewed version', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: 'Testing & approval' }).click()
  await dialog.getByLabel(`Arguments for ${name}`, { exact: true }).fill('{"term":"maize"}')
  await expect(dialog.getByRole('button', { name: `Enable operation ${name}`, exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: `Test operation ${name}`, exact: true }).click()
  await expect(dialog.getByRole('button', { name: `Approve exact version ${name}`, exact: true })).toBeEnabled({ timeout: 30000 })
  await dialog.getByRole('button', { name: `Approve exact version ${name}`, exact: true }).click()
  await dialog.getByRole('button', { name: `Enable operation ${name}`, exact: true }).click()
  await dialog.getByRole('tab', { name: 'Overview', exact: true }).click()
  await dialog.getByRole('button', { name: 'Enable connection', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Disable connection', exact: true })).toBeEnabled()
  await page.screenshot({ path: 'test-results-plugins/mcp-approved.png', fullPage: true })
})


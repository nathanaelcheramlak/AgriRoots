  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByRole('checkbox', { name: /Demo Farm F-001/ }).check()
  for (let i = 0; i < 5; i++) await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByRole('button', { name: 'Save monitor draft', exact: true }).click()
  await expect(wizard.getByRole('alert')).toContainText('Could not save on this device')
  await expect(wizard.getByRole('button', { name: 'Save monitor draft', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('agrilo-fieldops:monitoring:v1'))).toBeNull()

import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
async function createDraft(page: Page) {
  await page.goto('/#monitoring')
  await page.getByRole('button', { name: /Daily Weather & Rainfall Watch/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Create monitor' })
  await dialog.getByRole('textbox', { name: 'Monitor name', exact: true }).fill('Adama rainfall draft')
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await dialog.getByRole('checkbox', { name: /Demo Farm F-001/ }).check()
  await dialog.getByRole('checkbox', { name: /Demo Farm F-005/ }).check()
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Frequency', exact: true }).selectOption('weekly')
  await dialog.getByLabel('Timezone', { exact: true }).fill('UTC')
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await dialog.getByRole('spinbutton', { name: 'Threshold 1', exact: true }).fill('-1')
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Use 0–100')
  await dialog.getByRole('spinbutton', { name: 'Threshold 1', exact: true }).fill('20')
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(dialog.getByText('2 farms', { exact: false }).first()).toBeVisible()
  await dialog.getByRole('button', { name: 'Save monitor draft', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Adama rainfall draft', exact: true })).toBeVisible()
}
test('creates and reloads a local monitor, edits recurrence, duplicates, pauses and deletes without requests', async ({ page, baseURL }) => {
  const requests: string[] = [], errors: string[] = []
  page.on('request', r => { if (new URL(r.url()).origin !== new URL(baseURL!).origin) requests.push(r.url()) }); page.on('pageerror', e => errors.push(e.message))
  await createDraft(page)
  await expect(page.getByRole('main', { name: 'Monitoring workspace' }).getByText('Draft · Saved locally', { exact: true })).toBeVisible()
  await expect(page.getByText('No result', { exact: true })).toBeVisible()
  await page.reload(); await expect(page.getByRole('heading', { name: 'Adama rainfall draft', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Edit monitor draft' })
  await dialog.getByRole('button', { name: /Frequency/ }).click()
  await dialog.getByRole('combobox', { name: 'Frequency', exact: true }).selectOption('monthly')
  await dialog.getByRole('spinbutton', { name: 'Day of month', exact: true }).fill('15')
  await dialog.getByLabel('Timezone', { exact: true }).fill('Africa/Addis_Ababa')
  await dialog.getByRole('button', { name: /Review/ }).click()
  await dialog.getByRole('button', { name: 'Save monitor draft', exact: true }).click()
  await expect(page.getByText('Day 15 of each month at 08:00 · Africa/Addis_Ababa', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Adama rainfall draft (copy)', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause configuration', exact: true }).click()
  await expect(page.locator('.monitor-detail-badges').getByText('Paused locally', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Return to draft', exact: true }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Delete local monitor?' })
  await dialog.getByRole('button', { name: 'Delete local monitor', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your monitors', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('agrilo-fieldops:monitoring:v1')!).monitors.length)).toBe(1)
  expect(requests).toEqual([]); expect(errors).toEqual([])
})

import { test, expect, type Page } from '@playwright/test'
import { context, plotId } from '../tests/home-fixtures'
import { demoTerritory } from '../src/features/territory/fixtures'
import { rectangle } from '../src/features/territory/geometry'

async function openHome(page: Page, assigned = false) {
  await page.route('https://**/*', r => r.abort())
  await page.route('**/backend/**', r => {
    const path = new URL(r.request().url()).pathname
    if (path.endsWith('/api/auth/login')) return r.fulfill({ json: { access_token: 'territory-fixture-only', token_type: 'bearer', user: { user_id: context.user_id } } })
    if (path.endsWith('/companion/context')) return r.fulfill({ json: { ...context, ...(assigned ? { territory_workspace: { status: 'available', territories: [{ ...demoTerritory, id: 'backend-territory-one', name: 'Fixture assigned territory', origin: 'backend', status: 'assigned', officeId: context.office_id, authorizedPlotIds: [plotId], boundary: rectangle(38.7, 9, 38.8, 9.1) }, { ...demoTerritory, id: 'backend-territory-two', name: 'Fixture second assignment', origin: 'backend', status: 'assigned', officeId: context.office_id, authorizedPlotIds: [], boundary: rectangle(39.2, 8.5, 39.3, 8.6) }] } } : {}) } })
    if (path.endsWith('/providers') || path.endsWith('/integrations')) return r.fulfill({ json: { items: [] } })
    return r.fulfill({ status: 404, json: { detail: 'Unimplemented fixture route' } })
  })
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact: true }).fill('territory-fixture')
  await page.getByLabel('Password', { exact: true }).fill('territory-fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.field-map')).toBeVisible()
}
async function coordinates(page: Page, box: number[]) {
  const drawer = page.locator('.territory-drawer')
  await drawer.getByText('Enter boundary coordinates', { exact: true }).click()
  for (const [i, key] of ['west', 'south', 'east', 'north'].entries()) await drawer.getByLabel(key, { exact: true }).fill(String(box[i]))
  await drawer.getByRole('button', { name: 'Preview coordinates', exact: true }).click()
}
async function createTerritory(page: Page) {
  await page.getByRole('button', { name: 'Set Up My Territory', exact: true }).click()
  const drawer = page.locator('.territory-drawer')
  await drawer.getByLabel('Territory name', { exact: true }).fill('Test territory proposal')
  await drawer.getByLabel('Region', { exact: true }).fill('Test region')
  await drawer.getByLabel('District / administrative area', { exact: true }).fill('Test district')
  await coordinates(page, [39.2, 8.5, 39.3, 8.6])
  await drawer.getByRole('button', { name: 'Save Local Territory Draft', exact: true }).click()
  await page.getByRole('button', { name: 'Close territory panel', exact: true }).click()
}
async function registerPlot(page: Page, name = 'Synthetic maize plot', box = [39.24, 8.54, 39.241, 8.541]) {
  await page.getByRole('button', { name: 'Register Farm Plot', exact: true }).click()
  await expect(page.locator('.territory-map-mode')).toContainText('Draw farm plot draft')
  await page.keyboard.press('Escape')
  const drawer = page.locator('.territory-drawer')
  await drawer.getByLabel('Farm name / plot label', { exact: true }).fill(name)
  await coordinates(page, box)
  await drawer.getByRole('button', { name: 'Load synthetic farmer directory', exact: true }).click()
  await drawer.getByRole('checkbox', { name: /Synthetic Farmer 0001/ }).check()
  await drawer.getByRole('combobox', { name: 'Crop type', exact: true }).selectOption('Maize')
  await drawer.getByLabel('Planting date (if known)', { exact: true }).fill('2026-05-01')
  await drawer.getByRole('button', { name: 'Review registration', exact: true }).click()
  await drawer.getByRole('button', { name: 'Save Local Draft', exact: true }).click()
  await expect(drawer.getByRole('heading', { name, exact: true })).toBeVisible()
}
async function navigate(page: Page, name: string) {
  const mobile = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await mobile.isVisible()) await mobile.click()
  await page.getByRole('link', { name, exact: true }).click()
}

test('draws and edits a territory on the existing Leaflet map, preserving temporary analysis state', async ({ page }) => {
  await openHome(page)
  await page.getByRole('button', { name: 'My Territory', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome to Your Agricultural Workspace' })).toBeVisible()
  await expect(page.locator('.territory-drawer')).toContainText('territory assignments are not available yet')
  await page.locator('.territory-drawer').getByRole('button', { name: 'Set Up My Territory', exact: true }).click()
  const drawer = page.locator('.territory-drawer')
  await drawer.getByLabel('Territory name').fill('Drawn local territory')
  await drawer.getByLabel('Region', { exact: true }).fill('Test region')
  await drawer.getByLabel('District / administrative area').fill('Test district')
  await drawer.getByRole('button', { name: 'Draw rectangle', exact: true }).click()
  const map = (await page.locator('.field-map').boundingBox())!
  await page.mouse.click(map.x + map.width * .2, map.y + map.height * .7)
  await page.mouse.move(map.x + map.width * .75, map.y + map.height * .92, { steps: 7 })
  await page.mouse.click(map.x + map.width * .75, map.y + map.height * .92)
  await expect(drawer.getByRole('button', { name: 'Save Local Territory Draft' })).toBeEnabled()
  await expect(page.locator('.selection-card')).toHaveCount(0)
  const beforeEdit = await drawer.locator('.territory-geometry-preview').innerText()
  await drawer.getByRole('button', { name: 'Edit boundary on map', exact: true }).click()
  await expect(page.locator('.marker-icon.leaflet-marker-draggable').first()).toBeVisible()
  const handle = (await page.locator('.marker-icon.leaflet-marker-draggable').last().boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2 - 18, handle.y + handle.height / 2 - 18, { steps: 8 })
  await page.mouse.up()
  await page.locator('.territory-map-mode').getByRole('button', { name: 'Apply boundary', exact: true }).click()
  await expect(drawer.locator('.territory-geometry-preview')).not.toHaveText(beforeEdit, { useInnerText: true })
  await drawer.getByRole('button', { name: 'Save Local Territory Draft' }).click()
  await expect(drawer).toContainText('Local draft · not assigned')
  await page.getByRole('button', { name: 'Close territory panel' }).click()
  await page.getByLabel('LAT', { exact: true }).fill('8.55')
  await page.getByLabel('LNG', { exact: true }).fill('39.25')
  await page.getByRole('button', { name: 'Filter map area' }).click()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await page.getByRole('button', { name: 'My Territory', exact: true }).click()
  await expect(drawer.getByRole('heading', { name: 'Drawn local territory', exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Inspect territory boundary', exact: true }).click()
  await expect(page.locator('.field-map path[stroke="#8fc7a0"]')).toHaveCount(1)
  await page.screenshot({ path: 'test-results-layout/territory-drawing.png' })
})

test('registers separate plots, links the same synthetic farmer, preserves navigation and restores safe drafts', async ({ page }) => {
  const runRequests: string[] = []
  page.on('request', r => { if (r.method() === 'POST' && /\/runs$/.test(r.url())) runRequests.push(r.url()) })
  await openHome(page)
  await page.getByRole('checkbox', { name: /Fixture farm/ }).check()
  await createTerritory(page)
  await registerPlot(page)
  await expect(page.getByRole('main', { name: 'Live officer companion' })).toContainText('Live investigation requires a registered, authorized farm.')
  await expect(page.getByRole('button', { name: 'Start investigation', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Close territory panel' }).click()
  await registerPlot(page, 'Second synthetic plot', [39.25, 8.55, 39.251, 8.551])
  await page.getByRole('button', { name: /View Farmer/ }).click()
  await expect(page.locator('.territory-drawer')).toContainText('Associated farm plots (2)')
  await page.getByRole('button', { name: 'Close territory panel' }).click()
  for (const name of ['Plugins', 'Monitoring', 'Outreach']) { await navigate(page, name); await navigate(page, 'Home'); await expect(page.locator('.territory-home-toolbar')).toContainText('2 local plots') }
  expect(runRequests).toEqual([])
  await page.reload()
  await page.getByLabel('Phone number', { exact: true }).fill('territory-fixture')
  await page.getByLabel('Password', { exact: true }).fill('territory-fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.territory-home-toolbar')).toContainText('2 local plots')
  await expect(page.locator('.territory-home-toolbar')).toContainText('Local territory 1')
  await page.getByRole('button', { name: 'Farmers', exact: true }).click()
  await expect(page.locator('.territory-directory tbody tr')).toHaveCount(25)
  await page.getByLabel('Search farmers', { exact: true }).fill('Synthetic Farmer 0001')
  await expect(page.locator('.territory-directory tbody tr')).toHaveCount(1)
  await expect(page.locator('.territory-directory tbody')).toContainText('2')
})


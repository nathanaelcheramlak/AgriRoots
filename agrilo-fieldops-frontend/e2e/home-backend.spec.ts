import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test.skip(!process.env.AGRI_HOME_READY, 'Requires the explicitly isolated FastAPI/LangGraph browser fixture runner.')
async function signIn(page: import('@playwright/test').Page) {
  const login: { phone: string; password: string; fixture: boolean } = JSON.parse(readFileSync(process.env.AGRI_HOME_READY!, 'utf8'))
  expect(login.fixture).toBe(true)
  await page.route('https://**/*', route => route.abort()) // External basemap availability is not a fixture agriculture result.
  await page.goto('/#home')
  await page.getByLabel('Phone number', { exact: true }).fill(login.phone)
  await page.getByLabel('Password', { exact: true }).fill(login.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('main', { name: 'Live officer companion' })).toBeVisible()
}

test('real frontend → auth → authorized farm → durable LangGraph → two provider fixtures → evidence', async ({ page }) => {
  const submissions: Record<string, unknown>[] = []
  page.on('request', request => { if (request.method() === 'POST' && /\/skills\/[^/]+\/runs$/.test(new URL(request.url()).pathname)) submissions.push(request.postDataJSON()) })
  await signIn(page)
  await expect(page.getByTestId('map-count')).toHaveText('1 farm markers shown')
  await page.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact: true }).fill('Investigate the forecast and mapped soil of this farm. Explain the evidence and important limitations.')
  const created = page.waitForResponse(response => response.request().method() === 'POST' && /\/skills\/[^/]+\/runs$/.test(new URL(response.url()).pathname))
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  expect((await created).status()).toBe(202)
  await page.getByRole('link', { name: 'Plugins', exact: true }).click()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.locator('.live-run')).toHaveCount(1)
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Completed', { timeout: 30000 })
  await expect(page.locator('.live-evidence')).toHaveCount(2)
  await expect(page.getByText(/Fixture investigation: inspect/)).toBeVisible()
  await expect(page.getByRole('img', { name: /precipitation_sum:/ })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open source reference' })).toHaveCount(2)
  await page.screenshot({ path: 'test-results-home/home-integrated.png', fullPage: true })
  expect(submissions).toHaveLength(1)
  expect(submissions[0].plot_ids).toHaveLength(1)
  expect(submissions[0]).not.toHaveProperty('office_id')
  expect(submissions[0]).not.toHaveProperty('geometry')
  expect(submissions[0]).not.toHaveProperty('latitude')
  expect(await page.evaluate(() => Object.keys(localStorage).some(key => /token|session|password/i.test(key)))).toBe(false)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  await expect(page.locator('.live-evidence')).toHaveCount(0)
})

test('mobile Home preserves the real investigation when navigating away', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page)
  await page.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('link', { name: 'Plugins', exact: true }).click()
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /Synthetic plot A/ })).toBeChecked()
  await expect(page.getByTestId('map-count')).toHaveText('1 farm markers shown')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBe(true)
})

test('a provider HTTP failure remains a partial finding with only actual successful evidence', async ({ page }) => {
  await signIn(page)
  await page.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact: true }).fill('[fixture-provider-outage] Investigate weather and soil and report missing evidence.')
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Partially completed', { timeout: 30000 })
  await expect(page.getByText(/A?gricultural findings — partial evidence/i)).toBeVisible()
  await expect(page.getByText(/UPSTREAM_ERROR \/ INVALID/)).toBeVisible()
  await expect(page.locator('.live-evidence')).toHaveCount(1)
  await expect(page.getByText(/no successful soil result is assumed/)).toBeVisible()
  await page.locator('.live-chart').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results-home/home-evidence.png', fullPage: true })
})

test('cancellation is confirmed by the actual backend and does not submit another job', async ({ page }) => {
  await signIn(page)
  await page.getByRole('checkbox', { name: /Synthetic plot A/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the selected skill/ }).check()
  await page.getByRole('checkbox', { name: /Authorize the backend-configured model/ }).check()
  await page.getByLabel('Agricultural question', { exact: true }).fill('Investigate the forecast and soil for cancellation verification.')
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  const cancelled = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/cancel'))
  await page.getByRole('button', { name: 'Cancel investigation', exact: true }).click()
  const response = await cancelled
  expect(response.status()).toBe(200)
  expect((await response.json()).status).toBe('cancelled')
  await expect(page.locator('.live-run').getByRole('status')).toContainText('Cancelled')
  await expect(page.locator('.live-run')).toHaveCount(1)
})
